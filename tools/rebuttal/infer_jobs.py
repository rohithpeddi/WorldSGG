"""INFER: write (and optionally submit) the CS93371 GPU-queue job scripts for the rebuttal inference items.

    $PY tools/rebuttal/infer_jobs.py --stage gate|i12|i4|i3 [--only <row>...] [--submit]

Scripts are written to /data3/rohith/ag/runs/rebuttal/infer/jobs/<name>.sh; ``--submit`` copies each one to
<queue>/pending/<name>.tmp and renames it to <PP>_<name>.sh (BRIEF section 4). Priority band 10-29:
gate 10, i12 12-13, i4 16, i3 20-27 (the longest runs lowest).
"""
import argparse
import os
import shutil

Q = "/data3/rohith/ag/runs/rebuttal/queue"
O = "/data3/rohith/ag/runs/rebuttal/infer"
R = "/data3/rohith/ag/runs"
GATE_VIDEOS = "02DPI 03PRW"

# Table 2 rows: key of rescore_common_gt.DUMPS -> (config template, saved dump template); {m} = predcls|sgdet
ROWS = {
    "w_sttran": ("configs/methods/{m}/w_sttran_{m}_resnet50.yaml", R + "/rescore/dumps/w_sttran_{m}_resnet50__all.pkl"),
    "w_sttran_pp": ("configs/methods/{m}/w_sttran_pp_{m}_resnet50.yaml",
                    R + "/rescore/dumps/w_sttran_pp_{m}_resnet50__all.pkl"),
    "w_dsgdetr": ("configs/methods/{m}/w_dsgdetr_{m}_resnet50.yaml", R + "/rescore/dumps/w_dsgdetr_{m}_resnet50__all.pkl"),
    "w_dsgdetr_pp": ("configs/methods/{m}/w_dsgdetr_pp_{m}_resnet50.yaml",
                     R + "/rescore/dumps/w_dsgdetr_pp_{m}_resnet50__all.pkl"),
    "w_usg": ("configs/methods/{m}/w_usg_{m}_resnet50.yaml", R + "/rescore/dumps/w_usg_{m}_resnet50__all.pkl"),
    "worldwise_dinov3l": ("configs/methods/{m}/worldwise_{m}_dinov3l.yaml",
                          R + "/rescore/dumps/worldwise_{m}_dinov3l__all.pkl"),
    "worldwise_plus_dinov3tok": ("configs/methods/{m}/worldformer_c1_dinov3tok_{m}.yaml",
                                 R + "/worldformer/score/dumps/worldformer_c1_dinov3tok_{m}__all.pkl"),
    "worldwise_pp_dinov3": ("configs/methods/{m}/worldwise_pp_dinov3_{m}.yaml",
                            R + "/worldwise_pp/score/dumps/worldwise_pp_dinov3_{m}__all.pkl"),
}
ABLATIONS = ("notau", "nomask", "noema", "noego", "nomotion", "notempedge")

HEAD = """#!/bin/bash
# GPU_MEM_GB={mem}
# INFER rebuttal job {name} (generated by tools/rebuttal/infer_jobs.py)
set -e
cd $HOME/CODE/Scene4Cast_rebuttal
PY=$HOME/anaconda3/envs/scene4cast/bin/python
export OMP_NUM_THREADS=4 WSGG_REPO=$HOME/CODE/Scene4Cast_rebuttal PYTHONUNBUFFERED=1
O={O}
mkdir -p $O/gate $O/dumps $O/scores $O/score3d $O/abl $O/epochs
echo "[$(date -Is)] start {name} on $REB_HOST gpu $REB_GPU ($CUDA_VISIBLE_DEVICES)"
nvidia-smi --query-gpu=index,memory.used,memory.free --format=csv -i $CUDA_VISIBLE_DEVICES || true
rc=0
"""
TAIL = """echo "[$(date -Is)] end {name} rc=$rc"
exit $rc
"""


def dump_cmd(cfg, out, vis_off=False, keep3d=False, videos=None, videos_file=None, log=None):
    env = "WSGG_VISIBILITY_FROM_ANNOTATION=0 " if vis_off else ""
    extra = (" --keep-3d" if keep3d else "") + (f" --videos {videos}" if videos else "") \
        + (f" --videos-file {videos_file}" if videos_file else "")
    return (f"{env}$PY tools/dump_predictions.py --config {cfg} --ckpt best --frames all{extra} --out {out}"
            + (f" > {log} 2>&1" if log else ""))


def gate_job():
    name = "inf_gate"
    s = [HEAD.format(mem=6, name=name, O=O)]
    for row, (cfg_t, saved_t) in ROWS.items():
        for m in ("sgdet", "predcls"):
            cfg, saved = cfg_t.format(m=m), saved_t.format(m=m)
            a = f"$O/gate/{row}_{m}_a.pkl"
            s.append(f"echo '=== {row} {m}'")
            s.append(dump_cmd(cfg, a, keep3d=(m == "sgdet"), videos=GATE_VIDEOS) + " || rc=1")
            s.append(f"$PY tools/rebuttal/infer_gate.py --new {a} --saved {saved} --out $O/gate/{row}_{m}_a.json || rc=1")
            if m == "sgdet":
                b = f"$O/gate/{row}_{m}_b.pkl"
                s.append(dump_cmd(cfg, b, vis_off=True, keep3d=True, videos=GATE_VIDEOS) + " || rc=1")
                s.append(f"$PY tools/rebuttal/infer_gate.py --new {b} --saved {saved} --expect-vis-change "
                         f"--out $O/gate/{row}_{m}_b.json || rc=1")
                s.append(f"$PY tools/rebuttal/rescore_3d.py --dump {a} --name gate_{row} --out $O/gate --gate-only "
                         f"|| rc=1")
    s.append(TAIL.format(name=name))
    return {name: (10, "\n".join(s) + "\n")}


def i12_jobs(only=None):
    """Per Table 2 row: full SGDet dumps (a) default and (b) WSGG_VISIBILITY_FROM_ANNOTATION=0, both --keep-3d,
    then the 2-D common-GT scores of both (gate (a) vs the saved common_gt JSON) and the 3-D re-score of (a)."""
    jobs = {}
    for pri, (row, (cfg_t, _)) in zip((12, 12, 12, 12, 12, 12, 13, 13), ROWS.items()):
        if only and row not in only:
            continue
        name = f"inf_i12_{row}"
        cfg = cfg_t.format(m="sgdet")
        s = [HEAD.format(mem=6, name=name, O=O)]
        a, b = f"$O/dumps/{row}_sgdet_visgt.pkl", f"$O/dumps/{row}_sgdet_visoff.pkl"
        s.append(dump_cmd(cfg, a, keep3d=True, videos_file="$O/test1511_videos.txt", log=f"$O/dumps/{row}_sgdet_visgt.log"))
        s.append(f"$PY tools/rebuttal/infer_score.py --dump {a} --name {row}_sgdet_visgt --gate-exp {row} --out $O/scores "
                 f"|| rc=1")
        s.append(dump_cmd(cfg, b, vis_off=True, keep3d=True, videos_file="$O/test1511_videos.txt",
                          log=f"$O/dumps/{row}_sgdet_visoff.log"))
        s.append(f"$PY tools/rebuttal/infer_score.py --dump {b} --name {row}_sgdet_visoff --out $O/scores || rc=1")
        s.append(f"$PY tools/rebuttal/rescore_3d.py --dump {a} --name {row}_sgdet_visgt --out $O/score3d || rc=1")
        s.append(TAIL.format(name=name))
        jobs[name] = (pri, "\n".join(s) + "\n")
    return jobs


def i4_jobs(only=None):
    jobs = {}
    for x in ABLATIONS:
        if only and x not in only:
            continue
        name = f"inf_i4_{x}"
        s = [HEAD.format(mem=6, name=name, O=O)]
        for m in ("predcls", "sgdet"):
            cfg = f"configs/methods/{m}/worldwise_abl_{x}_{m}_dinov3l.yaml"
            d = f"$O/abl/worldwise_abl_{x}_{m}__all.pkl"
            s.append(dump_cmd(cfg, d, keep3d=(m == "sgdet"), videos_file="$O/test1511_videos.txt",
                              log=f"$O/abl/worldwise_abl_{x}_{m}.log"))
            s.append(f"$PY tools/rebuttal/infer_score.py --dump {d} --name abl_{x}_{m} --out $O/scores || rc=1")
        s.append(TAIL.format(name=name))
        jobs[name] = (16, "\n".join(s) + "\n")
    return jobs


def i3_jobs(only=None):
    """One epoch sweep per run (16); the longest runs get the lowest priority number (start first)."""
    pri = {"worldwise_pp_dinov3": 20, "worldwise_plus_dinov3tok": 22, "worldwise_dinov3l": 22}
    jobs = {}
    for row, (cfg_t, _) in ROWS.items():
        for m in ("predcls", "sgdet"):
            key = f"{row}_{m}"
            if only and row not in only and key not in only:
                continue
            name = f"inf_i3_{key}"
            cfg = cfg_t.format(m=m)
            s = [HEAD.format(mem=8, name=name, O=O)]
            s.append(f"$PY tools/rebuttal/epoch_sweep.py --config {cfg} --row {row} --out $O/epochs/{key}.json "
                     f"--workers 4 --loader-workers 2")
            s.append(TAIL.format(name=name))
            jobs[name] = (pri.get(row, 24) + (0 if m == "sgdet" else 1), "\n".join(s) + "\n")
    return jobs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", required=True, choices=["gate", "i12", "i4", "i3"])
    ap.add_argument("--only", nargs="*", default=None)
    ap.add_argument("--submit", action="store_true")
    a = ap.parse_args()
    jobs = {"gate": gate_job, "i12": i12_jobs, "i4": i4_jobs, "i3": i3_jobs}[a.stage]
    jobs = jobs() if a.stage == "gate" else jobs(a.only)
    os.makedirs(f"{O}/jobs", exist_ok=True)
    for name, (pri, text) in jobs.items():
        path = f"{O}/jobs/{name}.sh"
        with open(path, "w") as f:
            f.write(text)
        if a.submit:
            for d in ("pending", "running", "done", "failed"):
                if any(fn.endswith(f"_{name}.sh") or fn.endswith(f"__{pri:02d}_{name}.sh") for fn in os.listdir(f"{Q}/{d}")):
                    raise SystemExit(f"{name} already in {Q}/{d}; remove it from there first (own jobs only)")
            tmp = f"{Q}/pending/{name}.tmp"
            shutil.copy(path, tmp)
            os.rename(tmp, f"{Q}/pending/{pri:02d}_{name}.sh")
            print(f"submitted {pri:02d}_{name}.sh")
        else:
            print(f"wrote {path}")


if __name__ == "__main__":
    main()
